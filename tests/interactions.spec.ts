import { test, expect } from '@playwright/test'

test('terminal commands provide navigation, recover from unknown input, and clear history', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: testInfo.outputPath('redesign.png'), fullPage: true })
  const shell = page.getByRole('region', { name: 'Interactive portfolio terminal' })
  await shell.getByRole('button', { name: 'projects', exact: true }).click()
  await expect(shell.getByRole('status')).toContainText('ProjectFlow')
  await shell.getByRole('link', { name: /View selected work/ }).click()
  await expect(page).toHaveURL(/\/projects\/$/)
  await page.goto('/')
  await shell.getByLabel('Portfolio command').fill('unknown-command')
  await shell.getByRole('button', { name: 'Run command' }).click()
  await expect(shell.getByRole('status')).toContainText('Command not found')
  await shell.getByRole('button', { name: 'help', exact: true }).click()
  await expect(shell.getByRole('status')).toContainText('Try about, skills, projects')
  await shell.getByRole('button', { name: 'clear', exact: true }).click()
  await expect(shell.getByRole('status')).toBeEmpty()
})

test('motion control pauses decoration and remembers preference across reloads', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('.portrait-orbit').first()).toHaveCSS('animation-play-state', 'running')
  await page.getByRole('button', { name: 'Pause motion' }).click()
  await expect(page.locator('.portrait-orbit').first()).toHaveCSS('animation-play-state', 'paused')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Resume motion' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Resume motion' }).click()
  await expect(page.locator('.portrait-orbit').first()).toHaveCSS('animation-play-state', 'running')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.portrait-orbit').first()).toHaveCSS('animation-name', 'none')
  await expect(page.getByRole('button', { name: 'Pause motion' })).toBeHidden()
})
